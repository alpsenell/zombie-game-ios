    api.state.clock += 30;
    g.update(1 / 30);
    out.after = api.state.mapEvent; out.fogBack = api.scene.fog.color.getHex() === fog0;
    out.summary = api.runSummary().mapEvents;
    g.gameOver(); api.toMenu();
    api.startGame({ map: 'base' });
    for (let i = 0; i < 60; i++) g.update(1 / 30);
